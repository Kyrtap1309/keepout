"""Regenerate ``docs/validation.md`` and the README summary from CARA cases.

Usage: ``uv run python tools/validation_report.py [--check]``. Downloads the
pinned CARA files, runs every case, and writes both files; ``--check`` fails
instead of writing when either is out of date. Exits 1 if a case fails.
"""

from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from collections.abc import Sequence
from pathlib import Path

from keepout.pc.result import Method
from keepout.sources.cara import CARA_COMMIT
from keepout.validation.cases import load_all
from keepout.validation.evaluation import (
    ABSOLUTE_TOLERANCE,
    METHODS,
    RELATIVE_TOLERANCE,
    SMALL_PC,
    Outcome,
    evaluate,
)

REPO = Path(__file__).resolve().parents[1]

PAPER_TOLERANCE = 1e-3
"""Relative agreement with Alfano's published values (as in CARA's own tests)."""

PAPER_METHOD: Method = "foster"
"""Method compared with Alfano's published values."""

SUMMARY_START = "<!-- validation-summary:start -->"
SUMMARY_END = "<!-- validation-summary:end -->"

NOT_COMPARED = """\
## Not compared

- **Alfano case 12** has zero relative velocity: the encounter plane is
  undefined and CARA gives no 2-D value. keepout raises `GeometryError`.
- **Omitron inline cases** in CARA's `Pc2D_Foster_UnitTest.m` and
  `PcElrod_UnitTest.m` give states about 0.5 m from closest approach. CARA's
  2-D functions then place the full relative distance on the encounter plane;
  keepout projects the relative position onto the plane (the straight-line
  closest approach) and reports that the states are off TCA. The 53-CDM set
  above compares the two conventions where they coincide (CARA's `Pc2D`,
  computed after moving the states to TCA).
- **Alfano CDM files** (`DataFiles/SampleCDMs/AlfanoTestCase*.cdm`) give
  `RELATIVE_VELOCITY_*` in `[m]`; keepout rejects the unit, as CCSDS
  508.0-B-1 requires `[m/s]`.
"""


def _error(outcome: Outcome) -> str:
    error, relative, _ = outcome.verdict
    return f"{error:.1e}" if relative else f"{error:.1e} (abs)"


def _mark(passed: bool) -> str:
    return "pass" if passed else "**FAIL**"


def _worst(outcomes: Sequence[Outcome]) -> str:
    relative = [o.verdict.error for o in outcomes if o.verdict.relative]
    return f"{max(relative):.1e}" if relative else "-"


def render_summary(outcomes: Sequence[Outcome]) -> str:
    """Markdown table: per method, cases passed and worst relative error."""
    lines = [
        "| Method | Cases passed | Worst relative error |",
        "|---|---|---|",
    ]
    for method in METHODS:
        mine = [o for o in outcomes if o.method == method]
        passed = sum(o.passed for o in mine)
        lines.append(f"| {method} | {passed} / {len(mine)} | {_worst(mine)} |")
    return "\n".join(lines)


def _suite_table(outcomes: Sequence[Outcome]) -> list[str]:
    with_paper = any(o.case.paper is not None for o in outcomes)
    header = "| Case | HBR [m] | CARA Pc |" + "".join(
        f" {method.capitalize()} | error |" for method in METHODS
    )
    rule = "|---|---|---|" + "---|---|" * len(METHODS)
    if with_paper:
        header += " Alfano paper | vs paper |"
        rule += "---|---|"
    lines = [header, rule]
    by_case: defaultdict[str, dict[Method, Outcome]] = defaultdict(dict)
    for outcome in outcomes:
        by_case[outcome.case.case_id][outcome.method] = outcome
    for case_id, by_method in by_case.items():
        case = by_method[METHODS[0]].case
        row = (
            f"| {case_id} | {case.conjunction.hard_body_radius:g} "
            f"| {case.reference:.9e} |"
        ) + "".join(
            f" {o.value:.9e} | {_error(o)} {_mark(o.passed)} |"
            for o in (by_method[method] for method in METHODS)
        )
        if with_paper and case.paper is not None:
            paper_error = abs(by_method[PAPER_METHOD].value - case.paper) / case.paper
            row += (
                f" {case.paper:.9e} | {paper_error:.1e} "
                f"{_mark(paper_error <= PAPER_TOLERANCE)} |"
            )
        lines.append(row)
    return lines


def render_page(outcomes: Sequence[Outcome]) -> str:
    """The full ``docs/validation.md`` page."""
    suites: defaultdict[str, list[Outcome]] = defaultdict(list)
    for outcome in outcomes:
        suites[outcome.case.suite].append(outcome)
    parts = [
        "# Validation against NASA CARA",
        "",
        "Generated by `tools/validation_report.py` from "
        f"[CARA Analysis Tools](https://github.com/nasa/CARA_Analysis_Tools) "
        f"commit `{CARA_COMMIT[:12]}`. Do not edit by hand.",
        "",
        f"Criterion: relative error at most {RELATIVE_TOLERANCE:g} where the "
        f"CARA Pc is at least {SMALL_PC:g}, absolute error at most "
        f"{ABSOLUTE_TOLERANCE:g} below that, unless a case states its own "
        "tolerance.",
        "",
        "## Summary",
        "",
        render_summary(outcomes),
        "",
    ]
    for suite, members in suites.items():
        parts += [f"## {suite}", "", *_suite_table(members), ""]
    parts.append(NOT_COMPARED)
    return "\n".join(parts)


def replace_summary(readme: str, summary: str) -> str:
    """Put ``summary`` between the README's validation-summary markers.

    Raises
    ------
    ValueError
        If the markers are missing or out of order.
    """
    start = readme.find(SUMMARY_START)
    end = readme.find(SUMMARY_END)
    if start < 0 or end < start:
        raise ValueError(
            f"README needs {SUMMARY_START} and {SUMMARY_END}, in that order"
        )
    head = readme[: start + len(SUMMARY_START)]
    return f"{head}\n{summary}\n{readme[end:]}"


def rendered_files(
    outcomes: Sequence[Outcome], page: Path, readme: Path
) -> dict[Path, str]:
    """What the validation page and the README should contain for ``outcomes``."""
    return {
        page: render_page(outcomes),
        readme: replace_summary(
            readme.read_text(encoding="utf-8"), render_summary(outcomes)
        ),
    }


def main(argv: Sequence[str] | None = None) -> int:
    """Write (or with ``--check`` verify) the validation page and README summary.

    Returns
    -------
    int
        0 on success; 1 if a case fails or, with ``--check``, a file is stale.
    """
    parser = argparse.ArgumentParser(prog="tools/validation_report.py")
    parser.add_argument("--check", action="store_true", help="fail if out of date")
    parser.add_argument("--page", type=Path, default=REPO / "docs/validation.md")
    parser.add_argument("--readme", type=Path, default=REPO / "README.md")
    args = parser.parse_args(argv)

    outcomes = evaluate(load_all())
    status = 0
    for path, text in rendered_files(outcomes, args.page, args.readme).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            print(f"{path} is out of date; run tools/validation_report.py")
            status = 1
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path}")
    failed = [o for o in outcomes if not o.passed]
    for outcome in failed:
        print(f"FAIL {outcome.case.suite} {outcome.case.case_id} {outcome.method}")
    return 1 if failed else status


if __name__ == "__main__":
    sys.exit(main())
